NombreTrabajador = input("Ingrese el Nombre del Trabajador:")
Horastrabajadas = float (input("Ingrese la cantidad de horas trabajadas durante la semana:"))
PagoRecibido = float (input("Ingrese el pago recibido por cada hora de trabajo:"))

Salario = Horastrabajadas * PagoRecibido 

print ("Nombre del trabajador:", NombreTrabajador)
print ("Cantidad de horas trabajadas durante la semana:", Horastrabajadas)
print ("Pago recibido por cada hora de trabajo:", PagoRecibido)
print ("Salario semanal:", Salario)
